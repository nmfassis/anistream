#!/usr/bin/env bash
# anistream installer
#
#   curl -fsSL https://raw.githubusercontent.com/YOUR_GITHUB_USER/anistream/main/install.sh | bash
#   bash install.sh [--prefix DIR] [--ref BRANCH] [--uninstall]
#
# Works in Git Bash on Windows and on Linux/macOS. Needs Python 3.8+ (no pip, no dependencies).
# Run from a clone it installs the local files; otherwise it downloads the repo tarball.
set -euo pipefail

REPO="${ANISTREAM_REPO:-YOUR_GITHUB_USER/anistream}"
REF="${ANISTREAM_REF:-main}"
BIN="${ANISTREAM_BIN:-$HOME/.local/bin}"
DATA="${ANISTREAM_DATA:-$HOME/.local/share/anistream}"

say()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

case "$(uname -s 2>/dev/null)" in MINGW*|MSYS*|CYGWIN*) WIN=1 ;; *) WIN=0 ;; esac

UNINSTALL=0
while [ $# -gt 0 ]; do
  case "$1" in
    --uninstall|-u) UNINSTALL=1 ;;
    --prefix) shift; BIN="${1:?--prefix needs a folder}" ;;
    --ref) shift; REF="${1:?--ref needs a branch or tag}" ;;
    -h|--help) sed -n '2,7p' "$0" 2>/dev/null | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1" ;;
  esac
  shift
done

if [ "$UNINSTALL" = 1 ]; then
  rm -rf "$DATA" "$BIN/anistream" "$BIN/anistream.cmd"
  say "removed anistream (your settings were not touched)"
  exit 0
fi

# ---- source ------------------------------------------------------------------
SELF_DIR=""
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; fi
if [ -n "$SELF_DIR" ] && [ -f "$SELF_DIR/anistream/__init__.py" ]; then
  SRC="$SELF_DIR"
else
  case "$REPO" in YOUR_GITHUB_USER/*) die "set the repo first: ANISTREAM_REPO=user/repo bash install.sh (or edit REPO at the top of install.sh)";; esac
  TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
  URL="https://github.com/$REPO/archive/$REF.tar.gz"
  say "Downloading $URL"
  if command -v curl >/dev/null 2>&1; then curl -fsSL "$URL" -o "$TMP/src.tgz"
  elif command -v wget >/dev/null 2>&1; then wget -qO "$TMP/src.tgz" "$URL"
  else die "need curl or wget"; fi
  tar -xzf "$TMP/src.tgz" -C "$TMP"
  SRC="$(find "$TMP" -mindepth 1 -maxdepth 1 -type d | head -n1)"
  [ -f "$SRC/anistream/__init__.py" ] || die "download did not look like the anistream repo"
fi

# ---- python ------------------------------------------------------------------
find_python() {
  local c exe
  for c in python3 python py; do
    command -v "$c" >/dev/null 2>&1 || continue
    if [ "$c" = py ]; then set -- py -3; else set -- "$c"; fi
    exe="$("$@" -c 'import sys;print(sys.executable)' 2>/dev/null || true)"
    [ -n "$exe" ] || continue                       # skips the Microsoft Store stub
    "$@" -c 'import sys;sys.exit(sys.version_info<(3,8))' 2>/dev/null || continue
    printf '%s' "$exe"; return 0
  done
  return 1
}
PY="$(find_python)" || die "Python 3.8+ not found (Windows: winget install Python.Python.3.12)"

# ---- install -----------------------------------------------------------------
mkdir -p "$BIN" "$DATA"
rm -rf "$DATA/anistream"
cp -R "$SRC/anistream" "$DATA/anistream"
find "$DATA" -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null || true

if [ "$WIN" = 1 ] && command -v cygpath >/dev/null 2>&1; then
  PYU="$(cygpath -u "$PY")"; PYW="$(cygpath -w "$PY")"; APPW="$(cygpath -w "$DATA")"
else
  PYU="$PY"; PYW="$PY"; APPW="$DATA"
fi

# launchers point Python at the copied package; nothing is pip-installed
cat > "$BIN/anistream" <<LAUNCH
#!/bin/sh
# generated by anistream install.sh
PY='$PYU'
[ -x "\$PY" ] || PY="\$(command -v python3 || command -v python)"
PYTHONPATH='$APPW' exec "\$PY" -m anistream "\$@"
LAUNCH
chmod +x "$BIN/anistream"
if [ "$WIN" = 1 ]; then
  printf '@echo off\r\nrem generated by anistream install.sh\r\nset "PYTHONPATH=%s"\r\n"%s" -m anistream %%*\r\n' "$APPW" "$PYW" > "$BIN/anistream.cmd"
fi
say "Installed anistream -> $BIN/anistream  (Python: $PY)"

# ---- PATH --------------------------------------------------------------------
case ":$PATH:" in *":$BIN:"*) ;; *)
  RC="$HOME/.bashrc"; LINE='export PATH="$HOME/.local/bin:$PATH"'
  if [ "$BIN" = "$HOME/.local/bin" ]; then
    grep -qsF "$LINE" "$RC" || { printf '\n# added by anistream\n%s\n' "$LINE" >> "$RC"; say "Added $BIN to PATH in ~/.bashrc"; }
  else warn "$BIN is not on your PATH"; fi ;;
esac
if [ "$WIN" = 1 ] && command -v powershell >/dev/null 2>&1; then
  BINW="$(cygpath -w "$BIN")" powershell -NoProfile -Command '
    $d = $env:BINW; $p = [Environment]::GetEnvironmentVariable("Path","User"); if (-not $p) { $p = "" }
    if (-not (($p -split ";") | Where-Object { $_ -ieq $d })) {
      [Environment]::SetEnvironmentVariable("Path", ($p.TrimEnd(";") + ";" + $d), "User"); Write-Host "Added $d to your Windows user PATH (open a NEW terminal)." }' || true
fi

# ---- dependencies ------------------------------------------------------------
MISS=""
for t in mpv ani-cli-rs; do
  command -v "$t" >/dev/null 2>&1 || [ -x "$HOME/.local/bin/$t" ] || [ -x "$HOME/.local/bin/$t.exe" ] || MISS="$MISS $t"
done
if [ -n "$MISS" ]; then
  say ""; say "Still missing:$MISS"
  [ "$WIN" = 1 ] && say "  winget install mpv.mpv fzf   (fzf is optional)"
  case "$MISS" in *ani-cli-rs*) say "  ani-cli-rs: https://github.com/vorlie/ani-cli-rs/wiki/Installation" ;; esac
fi
say ""; say "Done. Open a new terminal and run: anistream doctor"
